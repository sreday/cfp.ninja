package api

import (
	"net/http"

	"github.com/sreday/cfp.ninja/pkg/config"
	"github.com/sreday/cfp.ninja/pkg/models"
)

// GameSignals is what the game reports about how a run was played, so runs
// played by a script or an AI agent can be told from runs played by a person.
// It comes from the browser, so it only catches agents that play openly; that
// is the point: an agent told to "play this and get a high score" should land
// on the AI agents board, and a person never should.
type GameSignals struct {
	Webdriver bool `json:"webdriver"` // the browser says it is under automation
	Untrusted int  `json:"untrusted"` // input events made by script, not by a device
	Slashes   int  `json:"slashes"`   // slashes that counted
	Teleports int  `json:"teleports"` // of those, long ones with no pointer path in between
	Cuts      int  `json:"cuts"`      // whole fruit cut by hand
	Clean     int  `json:"clean"`     // of those, cut dead centre
}

// GameHumans lists the users (by id) cleared on appeal: their runs always count
// as a person's, whatever the signals say. Add an id here to uphold an appeal;
// ApplyGameHumans then moves their agent score to the players' board at startup.
var GameHumans = map[uint]bool{}

// looksAutomated says whether a run was played by a script or an AI agent, and
// why. The rules are deliberately few and plain, so a verdict can be explained.
func looksAutomated(s GameSignals) (bool, string) {
	switch {
	case s.Webdriver:
		return true, "the browser was under automation"
	case s.Untrusted > 0:
		return true, "the input was generated by a script"
	case s.Slashes >= 15 && s.Teleports*2 > s.Slashes:
		return true, "most slashes jumped across the screen with no pointer movement in between"
	case s.Cuts >= 40 && s.Clean*100 >= s.Cuts*97:
		return true, "nearly every cut was dead centre"
	}
	return false, ""
}

// AppealGameScoreHandler records that the logged-in player says an automated
// verdict was wrong. Appeals are reviewed; an upheld one adds them to GameHumans.
func AppealGameScoreHandler(cfg *config.Config) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		user := GetUserFromContext(r.Context())
		if user == nil {
			encodeError(w, "Unauthorized", http.StatusUnauthorized)
			return
		}
		res := cfg.DB.Model(&models.GameScore{}).Where("user_id = ? AND agent_score > 0", user.ID).Update("appeal", true)
		if res.Error != nil {
			cfg.Logger.Error("failed to record game appeal", "user_id", user.ID, "error", res.Error)
			encodeError(w, "Failed to record the appeal", http.StatusInternalServerError)
			return
		}
		if res.RowsAffected == 0 {
			encodeError(w, "Nothing to appeal", http.StatusBadRequest)
			return
		}
		encodeResponse(w, r, map[string]interface{}{"ok": true})
	}
}

// GameAppealEntry is one open appeal: the player (by id, no name) and the ids of
// their recent runs that were judged automated, to be looked at again.
type GameAppealEntry struct {
	Player     uint   `json:"player"`
	AgentScore int    `json:"agent_score"`
	Traces     []uint `json:"traces"`
}

// ListGameAppealsHandler returns the open appeals for review.
func ListGameAppealsHandler(cfg *config.Config) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		var rows []models.GameScore
		if err := cfg.DB.Where("appeal = ? AND agent_score > 0", true).Order("updated_at ASC").Limit(50).Find(&rows).Error; err != nil {
			cfg.Logger.Error("failed to load game appeals", "error", err)
			encodeError(w, "Failed to load appeals", http.StatusInternalServerError)
			return
		}
		out := make([]GameAppealEntry, 0, len(rows))
		for _, row := range rows {
			var ids []uint
			cfg.DB.Model(&models.GameTrace{}).Where("user_id = ? AND agent = ?", row.UserID, true).Order("id DESC").Limit(5).Pluck("id", &ids)
			out = append(out, GameAppealEntry{Player: row.UserID, AgentScore: row.AgentScore, Traces: ids})
		}
		encodeResponse(w, r, map[string]interface{}{"appeals": out})
	}
}
